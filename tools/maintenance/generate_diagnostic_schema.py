"""Embed the checked-in diagnostic JSON Schema for standalone compiler builds."""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SOURCE = ROOT / "docs/schemas/uxb.diagnostics.v1.schema.json"
TARGET = ROOT / "src/common/diagnostic_schema_data.fbs"


def main():
    schema = json.loads(SOURCE.read_text(encoding="utf-8"))
    body = json.dumps(schema, ensure_ascii=False, separators=(",", ":"))
    lines = ["' Generated by tools/maintenance/generate_diagnostic_schema.py.",
             "' Source: docs/schemas/uxb.diagnostics.v1.schema.json",
             "#ifndef UXB_DIAGNOSTIC_SCHEMA_DATA_FBS",
             "#define UXB_DIAGNOSTIC_SCHEMA_DATA_FBS",
             "Function UXBDiagnosticSchemaJson(ByRef jsonOut As String) As Integer",
             '    jsonOut = ""']
    for start in range(0, len(body), 160):
        lines.append('    jsonOut &= "' + body[start:start + 160].replace('"', '""') + '"')
    lines += ["    Return 1", "End Function", "#endif", ""]
    TARGET.write_text("\n".join(lines), encoding="utf-8")
    print(f"Embedded {len(body)} schema characters")


if __name__ == "__main__":
    main()
