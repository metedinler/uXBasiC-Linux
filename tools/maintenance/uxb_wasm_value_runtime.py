"""Embed the readable WASM value runtime without changing JavaScript bytes."""
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
source = ROOT / 'runtime/wasm/ux_value_runtime.js'
target = ROOT / 'src/codegen/wasm/runtime/wasm_value_runtime_generated.fbs'


def generate():
    lines = ['\' Generated by tools/maintenance/uxb_wasm_value_runtime.py',
             'Private Function UXBWasmValueRuntimeJs() As String', '    Dim s As String']
    for line in source.read_text(encoding='utf-8').splitlines():
        lines.append('    s &= "' + line.replace('"', '""') + '" & Chr(10)')
    return '\n'.join(lines + ['    Return s', 'End Function', ''])


if __name__ == '__main__':
    import argparse
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    content = generate()
    if args.check:
        if target.read_text(encoding='utf-8') != content:
            raise SystemExit('WASM value runtime embed is stale')
    else:
        target.write_text(content, encoding='utf-8')
    wat_source = ROOT / 'runtime/wasm/ux_string_runtime.wat'
    wat_target = ROOT / 'src/codegen/wasm/runtime/wasm_string_runtime_generated.fbs'
    wat_lines = ["' Generated by tools/maintenance/uxb_wasm_value_runtime.py", 'Private Function UXBWasmStringRuntimeWat() As String', '    Dim s As String']
    for line in wat_source.read_text(encoding='utf-8').splitlines():
        wat_lines.append('    s &= "' + line.replace('"', '""') + '" & Chr(10)')
    wat_content = '\n'.join(wat_lines + ['    Return s', 'End Function', ''])
    if args.check:
        if wat_target.read_text(encoding='utf-8') != wat_content:
            raise SystemExit('WASM string runtime embed is stale')
    else:
        wat_target.write_text(wat_content, encoding='utf-8')
