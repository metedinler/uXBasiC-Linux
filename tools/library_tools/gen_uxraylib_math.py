#!/usr/bin/env python3
"""uxraylib raymath sarmalayici uretici (S-052, raylib Models/3D dilimi 1: CPU-tarafi matematik).

raymath.h'nin `RMAPI` islevlerini okur ve iki dosya uretir:
  runtime_ext/uxraylib/uxraylib_math.inc      C (uxraylib_adapter.c icinden #include edilir)
  libsx/uxraylib/uxraylib_math.bas            uXBasic `NAMESPACE uxraylib` sarmalayicilari

Sozlesme (uXBasic CALL(DLL) yalniz sayi/isaretci tasir, yapi degil):
  * float/double        -> F64 (C tarafinda float'a daralir; raylib float kullanir)
  * int                 -> I32
  * Vector2/3/4, Quaternion -> bilesenlere acilir: v1x, v1y[, v1z[, v1w]] (F64)
  * Matrix              -> I32 MATRIS TUTAMACI (0 = gecersiz). Matris ureten her islev YENI bir tutamac doner;
                           isi biten tutamac MatrixRelease ile birakilir.
  * Vector/Quaternion sonucu -> islev bir SUB'dur; sonuc "kayit"ta (register 0) durur: ResX/ResY/ResZ/ResW.
    Birden cok sonuc ureten islevler kayit 1 ve 2'yi de doldurur (ResGet(kayit, bilesen)).
  * 10 argumani asan islevler (Vector3CubicHermite/Barycenter, QuaternionCubicHermiteSpline) "yuva" varyanti ile
    sunulur: VectorSlotSet(yuva, x, y, z, w) ile girdiler yuvalara yazilir, islev yuva numaralariyla cagrilir.

Kullanim: python tools/library_tools/gen_uxraylib_math.py --root . [--raymath C:\\msys64\\ucrt64\\include\\raymath.h]
"""
from __future__ import annotations

import argparse
import re
from pathlib import Path

HEADER_DEFAULT = r"C:\msys64\ucrt64\include\raymath.h"

SIG_RE = re.compile(r"^RMAPI\s+(?P<ret>[A-Za-z0-9_ ]+?)\s+(?P<name>[A-Za-z0-9_]+)\((?P<args>[^)]*)\)\s*$")

VEC_COMPONENTS = {"Vector2": 2, "Vector3": 3, "Vector4": 4, "Quaternion": 4}
SCALAR = {"float", "double"}

# uXBasic anahtar sozcugu (S-128) ya da anlam karisikligi yaratan parametre adlari
PARAM_RENAME = {
    "start": "begin", "end": "finish", "sub": "amount", "left": "leftEdge", "right": "rightEdge",
    "top": "topEdge", "bottom": "bottomEdge", "min": "minValue", "max": "maxValue",
    "from": "fromVec", "to": "toVec", "add": "addend", "mul": "factor", "sub_": "amount",
    "in": "input", "out": "output", "step": "stepValue", "mat": "matrix", "x": "x", "y": "y", "z": "z",
}

# el ile yazilan (yapi/isaretci/10+ arguman) islevler: uretilmez
MANUAL = {
    "Vector3OrthoNormalize", "Vector3ToFloatV", "MatrixToFloatV", "QuaternionToAxisAngle", "MatrixDecompose",
    "Vector3CubicHermite", "Vector3Barycenter", "QuaternionCubicHermiteSpline",
}


def snake(name: str) -> str:
    out = re.sub(r"(?<=[a-z0-9])(?=[A-Z])", "_", name)
    out = re.sub(r"(?<=[A-Z])(?=[A-Z][a-z])", "_", out)
    return out.lower()


def parse_params(arg_text: str):
    arg_text = arg_text.strip()
    if arg_text in ("", "void"):
        return []
    params = []
    for part in arg_text.split(","):
        part = part.replace("const ", "").strip()
        m = re.match(r"^(?P<type>[A-Za-z0-9_]+)\s+(?P<name>\*?[A-Za-z0-9_]+)$", part)
        if not m:
            raise ValueError(f"parametre ayristirilamadi: {part!r}")
        params.append((m.group("type"), m.group("name")))
    return params


def flatten(ptype: str, pname: str):
    """(c_params, bas_params, c_call_expr) -- ad, C tipi, uXB tipi, ABI kodu"""
    pname = PARAM_RENAME.get(pname, pname)
    if ptype == "double":
        # MatrixFrustum/Perspective/Ortho hesabi double ile yapar: degeri daraltmadan gecir
        return [(pname, "double", "F64", "F64")], pname
    if ptype in SCALAR:
        return [(pname, "double", "F64", "F64")], f"(float){pname}"
    if ptype == "int":
        return [(pname, "int", "I32", "I32")], pname
    if ptype in VEC_COMPONENTS:
        n = VEC_COMPONENTS[ptype]
        comps = "xyzw"[:n]
        cps = [(f"{pname}{c}", "double", "F64", "F64") for c in comps]
        args = ", ".join(f"(float){pname}{c}" for c in comps)
        ctor = {"Vector2": "V2", "Vector3": "V3", "Vector4": "V4", "Quaternion": "V4"}[ptype]
        return cps, f"{ctor}({args})"
    if ptype == "Matrix":
        return [(pname, "int", "I32", "I32")], f"uxMatrixGet({pname})"
    raise ValueError(f"desteklenmeyen tip {ptype}")


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--root", default=".")
    ap.add_argument("--raymath", default=HEADER_DEFAULT)
    ns = ap.parse_args()
    root = Path(ns.root)
    header = Path(ns.raymath).read_text(encoding="utf-8")

    c_lines = [
        "/* GENERATED by tools/library_tools/gen_uxraylib_math.py from raymath.h -- do not edit. */",
        "/* raylib raymath: CPU-only math. Vector/Quaternion results land in register 0 (see uxraylib_res_get). */",
        "",
    ]
    b_lines = [
        "' Generated by tools/library_tools/gen_uxraylib_math.py from raymath.h -- do not edit.",
        "' raylib raymath (CPU only, no window needed). Vector/Quaternion results are read with ResX/ResY/ResZ/ResW;",
        "' Matrix values are HANDLES (I32, 0 = invalid): every Matrix-producing function returns a new handle -> MatrixRelease.",
        "NAMESPACE uxraylib",
        "",
    ]

    count = 0
    skipped = []
    for line in header.splitlines():
        m = SIG_RE.match(line.strip())
        if not m:
            continue
        name = m.group("name")
        ret = m.group("ret").strip()
        if name in MANUAL:
            skipped.append(name)
            continue
        if ret in ("float3", "float16"):
            skipped.append(name)
            continue
        params = parse_params(m.group("args"))
        cps = []
        call_args = []
        for ptype, pname in params:
            if pname.startswith("*"):
                raise ValueError(f"isaretci parametre el ile yazilmali: {name}")
            f_c, f_expr = flatten(ptype, pname)
            cps.extend(f_c)
            call_args.append(f_expr)
        if len(cps) > 10:
            raise ValueError(f"{name}: {len(cps)} argüman (>10) MANUAL listesine eklenmeli")

        cname = "uxraylib_" + snake(name)
        cparam_text = ", ".join(f"{t} {n}" for n, t, _, _ in cps) or "void"
        invoke = f"{name}({', '.join(call_args)})"
        if ret in SCALAR:
            c_lines.append(f"UX_EXPORT double {cname}({cparam_text}) {{ return (double){invoke}; }}")
            bas_ret = "F64"
        elif ret == "int":
            c_lines.append(f"UX_EXPORT int {cname}({cparam_text}) {{ return {invoke}; }}")
            bas_ret = "I32"
        elif ret in VEC_COMPONENTS:
            setter = {"Vector2": "uxSetV2", "Vector3": "uxSetV3", "Vector4": "uxSetV4", "Quaternion": "uxSetV4"}[ret]
            c_lines.append(f"UX_EXPORT void {cname}({cparam_text}) {{ {setter}(0, {invoke}); }}")
            bas_ret = "VOID"
        elif ret == "Matrix":
            c_lines.append(f"UX_EXPORT int {cname}({cparam_text}) {{ return uxMatrixPut({invoke}); }}")
            bas_ret = "I32"
        elif ret == "void":
            skipped.append(name)
            continue
        else:
            raise ValueError(f"{name}: desteklenmeyen donus {ret}")

        sig = ", ".join(f"{n} AS {b}" for n, _, b, _ in cps)
        types = ",".join(a for _, _, _, a in cps)
        names = ", ".join(n for n, _, _, _ in cps)
        tail = f', "{types}", {names}' if cps else ""
        if bas_ret == "VOID":
            b_lines.append(f"SUB {name}({sig})")
            b_lines.append(f'    CALL(DLL, "uxraylib.dll", "{cname}", VOID, CDECL{tail})')
            b_lines.append("END SUB")
        else:
            b_lines.append(f"FUNCTION {name}({sig}) AS {bas_ret}")
            b_lines.append(f'    RETURN CALL(DLL, "uxraylib.dll", "{cname}", {bas_ret}, CDECL{tail})')
            b_lines.append("END FUNCTION")
        count += 1

    b_lines.append("")
    b_lines.append("END NAMESPACE")
    (root / "runtime_ext/uxraylib/uxraylib_math.inc").write_text("\n".join(c_lines) + "\n", encoding="utf-8")
    (root / "libsx/uxraylib/uxraylib_math.bas").write_text("\n".join(b_lines) + "\n", encoding="utf-8")
    print(f"uretilen islev: {count}; el ile yazilacak/atlanan: {', '.join(skipped)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
